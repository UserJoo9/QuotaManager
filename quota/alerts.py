"""Alerts system for Quota Manager.

Stores alert records in an `alerts` SQLite table with full CRUD. Alerts are
generated by the system (policy conflicts, quota exceeded, enforcement
failures, etc.) and can be acknowledged/dismissed by admins via the API.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any

from quota.db import Database, audit_policy_log


async def init_alerts_tables(db: Database) -> None:
    """Create the alerts table if it doesn't exist."""
    await db.conn.execute("""
        CREATE TABLE IF NOT EXISTS alerts (
            alert_id    TEXT PRIMARY KEY,
            alert_type  TEXT NOT NULL,       -- policy_conflict, quota_exceeded, device_blocked, enforcement_failure, system_error
            severity    TEXT NOT NULL DEFAULT 'medium',  -- low, medium, high, critical
            title       TEXT NOT NULL,
            message     TEXT NOT NULL,
            target      TEXT NOT NULL DEFAULT '',  -- device, user, policy, app, domain, etc.
            target_id   TEXT NOT NULL DEFAULT '',
            acknowledged INTEGER NOT NULL DEFAULT 0,
            acknowledged_by TEXT NOT NULL DEFAULT '',
            acknowledged_at TEXT NOT NULL DEFAULT '',
            created_at  TEXT NOT NULL,
            expires_at  TEXT NOT NULL DEFAULT '',
            metadata    TEXT NOT NULL DEFAULT '{}'   -- JSON extra data
        )
    """)
    await db.conn.execute("CREATE INDEX IF NOT EXISTS idx_alerts_ack ON alerts(acknowledged)")
    await db.conn.execute("CREATE INDEX IF NOT EXISTS idx_alerts_created ON alerts(created_at)")
    await db.conn.commit()


async def create_alert(db: Database, alert_type: str, title: str, message: str,
                       severity: str = "medium", target: str = "", target_id: str = "",
                       expires_at: str = "", metadata: dict | None = None,
                       created_by: str = "system") -> dict[str, Any]:
    """Create a new alert. Returns the alert dict."""
    import json
    now = datetime.now(timezone.utc).isoformat()
    alert_id = f"alt_{uuid.uuid4().hex[:12]}"

    await db.conn.execute(
        """INSERT INTO alerts (alert_id, alert_type, severity, title, message,
                               target, target_id, acknowledged, acknowledged_by,
                               acknowledged_at, created_at, expires_at, metadata)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        (alert_id, alert_type, severity, title, message, target, target_id,
         0, "", "", now, expires_at, json.dumps(metadata or {}, ensure_ascii=False)),
    )
    await db.conn.commit()

    await audit_policy_log(db, "alert_create", alert_id, title,
                           actor=created_by,
                           details={"alert_type": alert_type, "severity": severity,
                                    "target": target, "target_id": target_id})

    return {
        "alert_id": alert_id,
        "alert_type": alert_type,
        "severity": severity,
        "title": title,
        "message": message,
        "target": target,
        "target_id": target_id,
        "acknowledged": False,
        "acknowledged_by": "",
        "acknowledged_at": "",
        "created_at": now,
        "expires_at": expires_at,
        "metadata": metadata or {},
    }


async def list_alerts(db: Database, acknowledged: bool | None = None,
                      severity: str | None = None, limit: int = 100) -> list[dict[str, Any]]:
    """List alerts, newest first. Optionally filter by ack state and severity."""
    import json
    query = "SELECT * FROM alerts WHERE 1=1"
    params: list[Any] = []
    if acknowledged is not None:
        query += " AND acknowledged = ?"
        params.append(1 if acknowledged else 0)
    if severity:
        query += " AND severity = ?"
        params.append(severity)
    query += " ORDER BY created_at DESC LIMIT ?"
    params.append(limit)

    cur = await db.conn.execute(query, params)
    rows = await cur.fetchall()
    desc = cur.description or []
    cols = [d[0] for d in desc]
    if not rows:
        return []

    return [
        {
            "alert_id": r[0],
            "alert_type": r[1],
            "severity": r[2],
            "title": r[3],
            "message": r[4],
            "target": r[5],
            "target_id": r[6],
            "acknowledged": bool(r[7]),
            "acknowledged_by": r[8],
            "acknowledged_at": r[9],
            "created_at": r[10],
            "expires_at": r[11],
            "metadata": json.loads(r[12] or "{}"),
        }
        for r in rows
    ]


async def get_alert(db: Database, alert_id: str) -> dict[str, Any] | None:
    """Get a single alert by id."""
    import json
    cur = await db.conn.execute("SELECT * FROM alerts WHERE alert_id = ?", (alert_id,))
    row = await cur.fetchone()
    if not row:
        return None
    cols = [d[0] for d in cur.description]
    r = dict(zip(cols, row))
    return {
        "alert_id": r["alert_id"],
        "alert_type": r["alert_type"],
        "severity": r["severity"],
        "title": r["title"],
        "message": r["message"],
        "target": r["target"],
        "target_id": r["target_id"],
        "acknowledged": bool(r["acknowledged"]),
        "acknowledged_by": r["acknowledged_by"],
        "acknowledged_at": r["acknowledged_at"],
        "created_at": r["created_at"],
        "expires_at": r["expires_at"],
        "metadata": json.loads(r["metadata"] or "{}"),
    }


async def ack_alert(db: Database, alert_id: str, acknowledged_by: str = "admin") -> bool:
    """Acknowledge an alert. Returns True if acknowledged."""
    import datetime as _dt
    now = _dt.datetime.now(timezone.utc).isoformat()
    cur = await db.conn.execute(
        """UPDATE alerts SET acknowledged = 1, acknowledged_by = ?, acknowledged_at = ?
           WHERE alert_id = ? AND acknowledged = 0""",
        (acknowledged_by, now, alert_id),
    )
    await db.conn.commit()
    if cur.rowcount > 0:
        await audit_policy_log(db, "alert_ack", alert_id, "acknowledged",
                               actor=acknowledged_by)
        return True
    return False


async def delete_alert(db: Database, alert_id: str, created_by: str = "admin") -> bool:
    """Delete an alert. Returns True if deleted."""
    cur = await db.conn.execute("DELETE FROM alerts WHERE alert_id = ?", (alert_id,))
    await db.conn.commit()
    deleted = cur.rowcount > 0
    if deleted:
        await audit_policy_log(db, "alert_delete", alert_id, "deleted",
                               actor=created_by)
    return deleted


async def alert_count_unacked(db: Database) -> int:
    """Return count of unacknowledged alerts."""
    cur = await db.conn.execute("SELECT COUNT(*) FROM alerts WHERE acknowledged = 0")
    row = await cur.fetchone()
    return int(row[0] or 0)